/* Builds the legacy copy at legacy/ from a git tag (default v-pre-musclemap),
 * so the pre-3D-muscle-map RepTrack keeps working at /reptrack/legacy/.
 *
 *   node scripts/build-legacy.mjs [tag]
 *
 * Both versions are served from the same origin, so by default they would
 * share IndexedDB, Cache Storage and a service worker. The copy is isolated:
 *   - its database is "reptrack-legacy", never "reptrack";
 *   - its service worker is legacy/sw.js, scoped to /reptrack/legacy/, with
 *     caches named "reptrack-legacy-…", and deletes only those;
 *   - its manifest has its own id, name and start_url, so installing it never
 *     replaces the main app;
 *   - it keeps the noindex meta tag;
 *   - legacy-boot.js copies the main database into its own once, on first
 *     launch, then shows a dismissible "data here is separate" banner. Any
 *     storage key it adds is prefixed "legacy:". (The app itself uses none.)
 * The main service worker (sw.js) in turn never answers for /legacy/.
 * Every edit asserts that what it replaces is there exactly once, so a later
 * tag with different code fails loudly instead of building a shared copy.
 * See DEPLOY.md.
 */

import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const TAG = process.argv[2] || 'v-pre-musclemap';
const OUT = join(ROOT, 'legacy');
const git = (...args) => execFileSync('git', args, { cwd: ROOT, maxBuffer: 64 * 1024 * 1024 });

function once(text, from, to, file) {
  const n = text.split(from).length - 1;
  if (n !== 1) throw new Error(`${file}: expected exactly one "${from}", found ${n}`);
  return text.replace(from, to);
}

const EDITS = {
  'js/db.js': (t, f) => once(t, "export const DB_NAME = 'reptrack';", "export const DB_NAME = 'reptrack-legacy';   // the legacy copy's own database (DEPLOY.md)", f),
  'sw.js': (t, f) => {
    const version = t.match(/const CACHE = 'reptrack-shell-(v\d+)';/)?.[1];
    if (!version) throw new Error('sw.js: CACHE not found');
    t = once(t, `const CACHE = 'reptrack-shell-${version}';`, `const CACHE = 'reptrack-legacy-shell-${version}';`, f);
    return once(t, 'names.filter((n) => n !== CACHE)', "names.filter((n) => n.startsWith('reptrack-legacy-') && n !== CACHE)", f);
  },
  'index.html': (t, f) => {
    t = once(t, '<title>RepTrack — offline gym tracker</title>', '<title>RepTrack (legacy)</title>', f);
    return once(t, '<script type="module" src="js/app.js"></script>', '<script type="module" src="legacy-boot.js"></script>', f);
  },
  'manifest.webmanifest': (t) => {
    const m = JSON.parse(t);
    Object.assign(m, { id: 'reptrack-legacy', name: 'RepTrack (legacy)', short_name: 'RepTrack (legacy)', start_url: './index.html', scope: './' });
    delete m.shortcuts;
    return `${JSON.stringify(m, null, 2)}\n`;
  }
};

/* Runs before the legacy app: copy the main database once, then start the
 * app, then show the banner. A failed or impossible copy never blocks the app. */
const BOOT = `/* Legacy copy boot (generated by scripts/build-legacy.mjs from ${TAG}).
 * Copies the main app's data into this copy's own database once, then starts
 * the app. After that the two are independent. See DEPLOY.md. */

const COPIED = 'legacy:copied';
const DISMISSED = 'legacy:bannerDismissed';
const store = {
  get(k) { try { return localStorage.getItem(k); } catch { return null; } },
  set(k, v) { try { localStorage.setItem(k, v); } catch { /* private mode: the copy may run again, harmlessly */ } }
};

/* Muscle ids the main app introduced after this version: map them back so the
 * copy's own muscle views still count that work. */
const BACK = { 'upper-back-lats': ['lats', 'upper-back'], traps: ['upper-back'] };
function oldMuscles(ex) {
  if (!Array.isArray(ex.primaryMuscles)) return ex;
  const map = (list) => [...new Set(list.flatMap((m) => BACK[m] || [m]))];
  const primary = map(ex.primaryMuscles);
  return { ...ex, primaryMuscles: primary, secondaryMuscles: map(ex.secondaryMuscles || []).filter((m) => !primary.includes(m)) };
}

function readAll(name) {
  return new Promise((resolve, reject) => {
    const req = indexedDB.open(name);             // no version: never upgrades the main database
    req.onerror = () => reject(req.error);
    req.onsuccess = () => {
      const db = req.result;
      const names = [...db.objectStoreNames];
      const out = {};
      const tx = db.transaction(names, 'readonly');
      for (const n of names) { const g = tx.objectStore(n).getAll(); g.onsuccess = () => { out[n] = g.result; }; }
      tx.oncomplete = () => { db.close(); resolve(out); };
      tx.onerror = () => reject(tx.error);
    };
  });
}

async function copyOnce() {
  if (store.get(COPIED)) return;
  if (typeof indexedDB?.databases !== 'function') { store.set(COPIED, 'unsupported'); return; }
  const dbs = await indexedDB.databases();
  // Never open "reptrack" unless it exists: opening creates an empty one.
  if (!dbs.some((d) => d.name === 'reptrack')) { store.set(COPIED, 'nothing-to-copy'); return; }
  if (dbs.some((d) => d.name === 'reptrack-legacy')) { store.set(COPIED, 'already-there'); return; }
  const data = await readAll('reptrack');
  const db = await import('./js/db.js');
  await db.importAll({
    app: 'reptrack',
    schemaVersion: db.SCHEMA_VERSION,
    exercises: (data.exercises || []).map(oldMuscles),
    sessions: data.sessions || [],
    sets: data.sets || [],
    runs: data.runs || [],
    plans: data.plans || [],
    settings: data.settings || []
  }, { mode: 'replace' });
  store.set(COPIED, new Date().toISOString());
}

function banner() {
  if (store.get(DISMISSED)) return;
  const bar = document.createElement('div');
  bar.id = 'legacy-banner';
  bar.setAttribute('role', 'status');
  bar.style.cssText = 'display:flex;align-items:center;gap:12px;padding:10px 16px;background:var(--surface-2);color:var(--text);border-bottom:1px solid var(--border);font-size:.9rem';
  const text = document.createElement('p');
  text.style.cssText = 'margin:0;flex:1';
  text.textContent = 'Legacy version: data here is separate from the main app.';
  const close = document.createElement('button');
  close.type = 'button';
  close.className = 'btn btn-sm';
  close.id = 'legacy-banner-dismiss';
  close.setAttribute('aria-label', 'Dismiss the legacy version notice');
  close.textContent = 'Dismiss';
  close.addEventListener('click', () => { store.set(DISMISSED, '1'); bar.remove(); });
  bar.append(text, close);
  document.body.prepend(bar);
}

try { await copyOnce(); } catch (error) { console.warn('Legacy copy: could not copy the main data; starting empty.', error); store.set(COPIED, 'failed'); }
await import('./js/app.js');
banner();
`;

rmSync(OUT, { recursive: true, force: true });
const files = git('ls-tree', '-r', '--name-only', TAG, '--', 'index.html', 'manifest.webmanifest', 'sw.js', 'css', 'js', 'icons')
  .toString().trim().split('\n').filter(Boolean);
for (const file of files) {
  let content = git('show', `${TAG}:${file}`);
  if (EDITS[file]) content = EDITS[file](content.toString('utf8'), file);
  const dest = join(OUT, file);
  mkdirSync(dirname(dest), { recursive: true });
  writeFileSync(dest, content);
}
writeFileSync(join(OUT, 'legacy-boot.js'), BOOT);
// The legacy worker must precache its boot file too, or an offline start is blank.
const swPath = join(OUT, 'sw.js');
const sw = readFileSync(swPath, 'utf8');
writeFileSync(swPath, once(sw, "  './index.html',", "  './index.html',\n  './legacy-boot.js',", 'sw.js'));
console.log(`legacy/ built from ${TAG}: ${files.length + 1} files`);
